const STORE_KEY = 'eigentrust-lang'

export function detectLanguage() {
    const param = new URLSearchParams(location.search).get('lang')
    if (param && STRINGS[param]) return param
    try {
        const saved = localStorage.getItem(STORE_KEY)
        if (saved && STRINGS[saved]) return saved
    } catch {}
    for (const tag of navigator.languages || [navigator.language]) {
        const base = String(tag).toLowerCase().split('-')[0]
        if (STRINGS[base]) return base
    }
    return 'en'
}

export function saveLanguage(lang) {
    try { localStorage.setItem(STORE_KEY, lang) } catch {}
}

let current = 'en'

export const lang = () => current

export function setLanguage(code) {
    current = STRINGS[code] ? code : 'en'
    document.documentElement.lang = current
    document.documentElement.dir = RTL.has(current) ? 'rtl' : 'ltr'
    applyDom()
}

// t('key', { n: 3 }) with {placeholders}; missing keys fall back to English
export function t(key, vars = {}) {
    const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
}

export const num = (n, opts) => Number(n).toLocaleString(current, opts)

function applyDom() {
    document.title = t('title')
    document.querySelector('meta[name="description"]')?.setAttribute('content', t('description'))
    for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n)
    for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml)
    for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria))
}
